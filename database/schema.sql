DROP DATABASE IF EXISTS URBAN_EYE;
CREATE DATABASE URBAN_EYE CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci; -- stores Sinhala and Tamil text
USE URBAN_EYE;

CREATE TABLE COUNCIL(
    COUNCIL_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    COUNCIL_NAME VARCHAR(100) NOT NULL UNIQUE,
    COUNCIL_TYPE ENUM('Municipal Council') NOT NULL,
    DISTRICT VARCHAR(60) NOT NULL,
    PROVINCE VARCHAR(60) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP -- TIMESTAMP date and time (data type), DEFAULT CURRENT_TIMESTAMP if don't fill it, it fill default with current date and time

)ENGINE=InnoDB; -- IN THIS ENGINE STORES THIS TABLE

CREATE TABLE WARD( 
    WARD_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, -- unsigned for not negative numbers
    COUNCIL_ID INT UNSIGNED NOT NULL, 
    DESCRIPTION VARCHAR(255) NULL, 
    WARD_NAME VARCHAR(100) NOT NULL,
    CONSTRAINT UQ_WARD_PER_COUNCIL UNIQUE (COUNCIL_ID, WARD_NAME), -- UNIQE KEY is used for forbids duplicates
    CONSTRAINT WARD_COUNCIL FOREIGN KEY (COUNCIL_ID) REFERENCES COUNCIL (COUNCIL_ID) 
    ON UPDATE CASCADE -- KEEP THE CHILD ROWS IN SYNC WHEN PARENT ID CHANGES
    ON DELETE RESTRICT -- PROTECT PARENT ROWS FROM DELETION WHILE CHILDREN EXISTS
    
)ENGINE= InnODB;

CREATE TABLE CITIZEN(
    CITIZEN_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    WARD_ID  INT UNSIGNED NOT NULL,
    NIC_HASH CHAR(64) NOT NULL UNIQUE, -- CHAR IS USED FOR FIXED LENGTH CODES
    FULL_NAME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NULL UNIQUE,
    MOBILE_NUMBER VARCHAR(15) NOT NULL,
    ADDRESS VARCHAR(255) NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREDIBILITY_SCORE INT NOT NULL DEFAULT 100,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1, -- TINYINT means 1 byte of integer type storage
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CITIZEN_WARD FOREIGN KEY (WARD_ID) REFERENCES WARD(WARD_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT

)ENGINE= InnoDB;

CREATE TABLE OFFICER(
    OFFICER_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    COUNCIL_ID INT UNSIGNED NOT NULL,
    WARD_ID INT UNSIGNED NULL,
    EMPLOYEE_ID VARCHAR(50) NOT NULL UNIQUE,
    FULL_NAME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    DEPARTMENT VARCHAR(100) NULL,
    ROLE ENUM('Field Officer', 'Supervisor', 'Admin') NOT NULL DEFAULT 'Field Officer',
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT OFFICER_COUNCIL FOREIGN KEY (COUNCIL_ID) REFERENCES COUNCIL (COUNCIL_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
    CONSTRAINT OFFICER_WARD FOREIGN KEY (WARD_ID) REFERENCES WARD (WARD_ID)
    ON UPDATE CASCADE
    ON DELETE SET NULL 
    
)ENGINE= InnoDB;

CREATE TABLE ISSUE(
    ISSUE_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CITIZEN_ID INT UNSIGNED NOT NULL,
    WARD_ID INT UNSIGNED NOT NULL,
    OFFICER_ID INT UNSIGNED NULL,
    TITLE VARCHAR(150) NOT NULL,
    DESCRIPTION TEXT NOT NULL, -- It is a data type that stores large amounts of text
    CATEGORY ENUM('Road Hazard', 'Water Drainage','Waste Management', 'Street Lighting', 'Other') NOT NULL,
    STATUS ENUM ('Open', 'In Progress', 'Resolved','Closed','Disputed') NOT NULL DEFAULT 'Open',
    IS_EMERGENCY TINYINT(1) NOT NULL DEFAULT 0,
    PRIORITY_SCORE INT NOT NULL DEFAULT 0,
    BEFORE_PHOTO VARCHAR(500) NULL, -- Cloudinary image URL    CLOSURE_TYPE ENUM('Reporter Confirmed', 'Auto Closed') NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    RESOLVED_AT DATETIME NULL,
    CLOSED_AT DATETIME NULL,
    KEY IDX_ISSUE_DUP (WARD_ID, CATEGORY, CREATED_AT),
    CONSTRAINT ISSUE_CITIZEN FOREIGN KEY (CITIZEN_ID) REFERENCES CITIZEN (CITIZEN_ID)    CONSTRAINT ISSUE_CITIZEN FOREIGN KEY (CITIZEN_ID) REFERENCES CITIZEN (CITIZEN_ID) 
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
    CONSTRAINT ISSUE_WARD FOREIGN KEY (WARD_ID) REFERENCES WARD (WARD_ID) 
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
    CONSTRAINT ISSUE_OFFICER FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER(OFFICER_ID) 
    ON UPDATE CASCADE
    ON DELETE SET NULL

)ENGINE= InnoDB;

CREATE TABLE VOTE(
    VOTE_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISSUE_ID INT UNSIGNED NOT NULL,
    CITIZEN_ID INT UNSIGNED NOT NULL,
    VOTE_TYPE TINYINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_VOTE_ONCE UNIQUE (ISSUE_ID, CITIZEN_ID),
    CONSTRAINT CHK_VOTE_TYPE CHECK (VOTE_TYPE IN (-1, 1)),
    CONSTRAINT VOTE_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES ISSUE (ISSUE_ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
    CONSTRAINT VOTE_CITIZEN FOREIGN KEY (CITIZEN_ID) REFERENCES CITIZEN (CITIZEN_ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE COMMENT (
    COMMENT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISSUE_ID INT UNSIGNED NOT NULL,
    CITIZEN_ID INT UNSIGNED NULL,
    OFFICER_ID INT UNSIGNED NULL,
    BODY TEXT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY IDX_COMMENT_ISSUE (ISSUE_ID, CREATED_AT),
    KEY IDX_COMMENT_CITIZEN (CITIZEN_ID),
    KEY IDX_COMMENT_OFFICER (OFFICER_ID),
    CONSTRAINT CHK_COMMENT_AUTHOR CHECK(
        (CITIZEN_ID IS NOT NULL AND OFFICER_ID IS NULL) OR 
        (CITIZEN_ID IS NULL AND OFFICER_ID IS NOT NULL)    
        ),
    CONSTRAINT COMMENT_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES ISSUE (ISSUE_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT COMMENT_CITIZEN  FOREIGN KEY (CITIZEN_ID) REFERENCES CITIZEN (CITIZEN_ID),
    CONSTRAINT COMMENT_OFFICER  FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER (OFFICER_ID)
) ENGINE= InnoDB;

CREATE TABLE EMERGENCY_ALERT (
    ALERT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISSUE_ID INT UNSIGNED NOT NULL UNIQUE,
    OFFICER_ID INT UNSIGNED NULL,
    MESSAGE VARCHAR(255) NULL,
    OUTCOME ENUM('Pending', 'Confirmed','Declassified') NOT NULL DEFAULT ('Pending'),
    SENT_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ACKNOWLEDGE_AT DATETIME NULL,
    KEY IDX_ALERT_PENDING (OUTCOME, SENT_AT),
    KEY IDX_ALERT_OFFICER (OFFICER_ID),
    CONSTRAINT ALERT_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES ISSUE (ISSUE_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ALERT_OFFICER FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER (OFFICER_ID) 
    ON UPDATE CASCADE ON DELETE SET NULL
)ENGINE=InnoDB;

CREATE TABLE RESOLUTION_PROOF(
    PROOF_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISSUE_ID INT UNSIGNED NOT NULL,
    OFFICER_ID INT UNSIGNED NOT NULL,
    AFTER_PHOTO VARCHAR(500) NOT NULL,
    REMARKS TEXT NULL,
    SUBMITTED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY IDX_PROOF_ISSUE (ISSUE_ID, SUBMITTED_AT),
    KEY IDX_PROOF_OFFICER (OFFICER_ID),
    CONSTRAINT PROOF_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES ISSUE (ISSUE_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT PROOF_OFFICER FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER(OFFICER_ID)
    ON UPDATE CASCADE ON DELETE RESTRICT
)ENGINE=InnoDB;

CREATE TABLE REPORT_VERIFICATION(
    VERIFICATION_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISSUE_ID INT UNSIGNED NOT NULL,
    PROOF_ID INT UNSIGNED NOT NULL UNIQUE,
    REPORTER_ID INT UNSIGNED NOT NULL,
    RESPONSE ENUM('Pending','Confirmed','Disputed','auto_closed') NOT NULL DEFAULT 'Pending',
    DISPUTE_PHOTO VARCHAR(500) NULL,
    REMARKS VARCHAR(500) NULL,
    DEADLINE_AT DATETIME NOT NULL,
    REMINDER_7D_SENT TINYINT(1) NOT NULL DEFAULT 0,
    REMINDER_13d_SENT TINYINT(1) NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESPONDED_AT DATETIME NULL,
    KEY IDX_VERIFICATION_ISSUE (ISSUE_ID),
    KEY IDX_VERIFICATION_REPORTER (REPORTER_ID),
    KEY IDX_VERIFICATION_CRON (RESPONSE, DEADLINE_AT),
    CONSTRAINT VER_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES ISSUE (ISSUE_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT VER_PROOF FOREIGN KEY (PROOF_ID) REFERENCES RESOLUTION_PROOF (PROOF_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT VER_REPORTER FOREIGN KEY (REPORTER_ID) REFERENCES CITIZEN (CITIZEN_ID)
    ON UPDATE CASCADE ON DELETE CASCADE
)ENGINE=InnoDB;

CREATE TABLE ANNOUNCEMENT(
    ANNOUNCEMENT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    COUNCIL_ID INT UNSIGNED NOT NULL,
    WARD_ID INT UNSIGNED NULL,
    OFFICER_ID INT UNSIGNED NOT NULL,
    TITLE VARCHAR(150) NOT NULL,
    BODY TEXT NOT NULL,
    CATEGORY ENUM('Maintenance','Safety','Utility') NOT NULL,
    IS_PINNED TINYINT(1) NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    EXPIRES_AT DATETIME NULL,
    KEY IDX_ANN_WARD_FEED (WARD_ID, IS_PINNED,CREATED_AT),
    KEY IDX_ANN_COUNCIL (COUNCIL_ID),
    KEY IDX_ANN_OFFICER (OFFICER_ID),
    CONSTRAINT ANN_COUNCIL FOREIGN KEY (COUNCIL_ID) REFERENCES COUNCIL(COUNCIL_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ANN_WARD FOREIGN KEY (WARD_ID) REFERENCES WARD (WARD_ID)
    ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ANN_OFFICER FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER (OFFICER_ID)
    ON UPDATE CASCADE ON DELETE CASCADE
)ENGINE=InnoDB;

