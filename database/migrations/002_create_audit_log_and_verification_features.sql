-- Adds AUDIT_LOG table for the audit trail system, adds CLOSURE_TYPE to ISSUE,
-- and ensures reminder flag columns are present.

USE URBAN_EYE;

-- 1. Add CLOSURE_TYPE to ISSUE table if not already present
-- In MySQL 8.0.19+, ADD COLUMN IF NOT EXISTS is supported
SET @col_exists = (
    SELECT COUNT(*) 
    FROM INFORMATION_SCHEMA.COLUMNS 
    WHERE TABLE_SCHEMA = DATABASE() 
      AND TABLE_NAME = 'ISSUE' 
      AND COLUMN_NAME = 'CLOSURE_TYPE'
);

SET @sql_closure = IF(@col_exists = 0,
    "ALTER TABLE ISSUE ADD COLUMN CLOSURE_TYPE ENUM('Reporter Confirmed', 'Auto Closed') NULL AFTER BEFORE_PHOTO",
    "SELECT 'CLOSURE_TYPE already exists' AS info"
);
PREPARE stmt_closure FROM @sql_closure;
EXECUTE stmt_closure;
DEALLOCATE PREPARE stmt_closure;

-- 2. Create AUDIT_LOG table for enterprise audit trail
CREATE TABLE IF NOT EXISTS AUDIT_LOG (
    LOG_ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ENTITY_TYPE ENUM('ISSUE', 'REPORT_VERIFICATION', 'RESOLUTION_PROOF', 'CITIZEN', 'OFFICER', 'EMERGENCY_ALERT', 'COMMENT', 'VOTE', 'ANNOUNCEMENT', 'SYSTEM') NOT NULL,
    ENTITY_ID INT UNSIGNED NULL,
    ACTION VARCHAR(60) NOT NULL,
    PERFORMED_BY_TYPE ENUM('CITIZEN', 'OFFICER', 'ADMIN', 'SYSTEM') NOT NULL,
    PERFORMED_BY_ID INT UNSIGNED NULL,
    OLD_STATE JSON NULL,
    NEW_STATE JSON NULL,
    DETAILS JSON NULL,
    IP_ADDRESS VARCHAR(45) NULL,
    USER_AGENT VARCHAR(255) NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY IDX_AUDIT_ENTITY (ENTITY_TYPE, ENTITY_ID),
    KEY IDX_AUDIT_ACTION (ACTION),
    KEY IDX_AUDIT_PERFORMER (PERFORMED_BY_TYPE, PERFORMED_BY_ID),
    KEY IDX_AUDIT_CREATED (CREATED_AT)
) ENGINE=InnoDB;
